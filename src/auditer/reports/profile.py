from __future__ import annotations

from datetime import datetime, timezone

from auditer.models import ProfileData


def _format_event(event: dict) -> str | None:
    """Map a GitHub event to a human-readable line. Returns None for unsupported types."""
    event_type = event.get("type", "")
    repo_name = event.get("repo", {}).get("name", "")
    repo_url = f"https://github.com/{repo_name}"
    payload = event.get("payload", {})

    if event_type == "PushEvent":
        return f"Pushed to [{repo_name}]({repo_url})"
    if event_type == "PullRequestEvent":
        action = payload.get("action", "")
        if action == "opened":
            number = payload.get("pull_request", {}).get("number", "")
            return f"Opened PR #{number} in [{repo_name}]({repo_url})"
        return None
    if event_type == "CreateEvent":
        ref_type = payload.get("ref_type", "")
        if ref_type == "repository":
            return f"Created [{repo_name}]({repo_url})"
        return None
    if event_type == "IssuesEvent":
        action = payload.get("action", "")
        if action == "opened":
            number = payload.get("issue", {}).get("number", "")
            return f"Opened issue #{number} in [{repo_name}]({repo_url})"
        return None
    if event_type == "WatchEvent":
        return f"Starred [{repo_name}]({repo_url})"
    if event_type == "ForkEvent":
        return f"Forked [{repo_name}]({repo_url})"
    return None


def _language_bar(percentage: float, max_width: int = 25) -> str:
    """Build a proportional block character bar."""
    filled = max(0, min(max_width, round(percentage / 100 * max_width)))
    return "\u2588" * filled


def generate_profile_readme(data: ProfileData) -> str:
    """Generate a Markdown profile README from ProfileData."""
    lines: list[str] = []
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    # 1. Header
    display_name = data.name or data.username
    lines.append(f"# Hi, I'm {display_name}")
    lines.append("")
    lines.append(f"[GitHub Profile]({data.html_url})")
    lines.append("")

    # 2. About
    about_items: list[str] = []
    if data.location:
        about_items.append(f"- Location: {data.location}")
    if data.company:
        about_items.append(f"- Company: {data.company}")
    if data.blog:
        about_items.append(f"- Blog: {data.blog}")
    if data.twitter_username:
        about_items.append(f"- Twitter: [@{data.twitter_username}](https://twitter.com/{data.twitter_username})")

    if data.bio or about_items:
        lines.append("## About")
        lines.append("")
        if data.bio:
            lines.append(data.bio)
            lines.append("")
        for item in about_items:
            lines.append(item)
        if about_items:
            lines.append("")

    # 3. Stats
    lines.append("## Stats")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---|")
    lines.append(f"| Public repos | {data.public_repos_count} |")
    lines.append(f"| Total stars | {data.total_stars} |")
    lines.append(f"| Total forks | {data.total_forks} |")
    lines.append(f"| Followers | {data.followers} |")
    lines.append(f"| Following | {data.following} |")
    lines.append("")

    # 4. Top Repositories
    pinned = data.pinned_repos
    if pinned:
        lines.append("## Top Repositories")
        lines.append("")
        lines.append("| Repository | Description | Language | Stars | Forks |")
        lines.append("|---|---|---|---|---|")
        for r in pinned:
            desc = r.description or "\u2014"
            lang = r.language or "\u2014"
            lines.append(f"| [{r.name}]({r.url}) | {desc} | {lang} | {r.stars} | {r.forks} |")
        lines.append("")

    # 5. Languages
    breakdown = data.language_breakdown
    if breakdown:
        lines.append("## Languages")
        lines.append("")
        lines.append("| Language | Repos | % |")
        lines.append("|---|---|---|")
        for lang, count, pct in breakdown:
            lines.append(f"| {lang} | {count} | {pct}% |")
        lines.append("")
        lines.append("```")
        max_lang_len = max(len(lang) for lang, _, _ in breakdown)
        for lang, _, pct in breakdown:
            bar = _language_bar(pct)
            lines.append(f"{lang:<{max_lang_len}}  {bar} {pct}%")
        lines.append("```")
        lines.append("")

    # 6. Recent Activity
    activity_lines: list[str] = []
    for event in data.events[:10]:
        formatted = _format_event(event)
        if formatted:
            activity_lines.append(f"- {formatted}")

    if activity_lines:
        lines.append("## Recent Activity")
        lines.append("")
        lines.extend(activity_lines)
        lines.append("")

    # Footer
    lines.append(f"_Generated by GitHub Auditer on {now}_")
    lines.append("")

    return "\n".join(lines)
